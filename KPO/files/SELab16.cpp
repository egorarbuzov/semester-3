// Лабораторная работа №16. Разработка лексического распознавателя (II часть)
//
// Автомат, который тестируется ниже, разбирает язык  (a+b)*aba
// Граф переходов (4 состояния):
//
//   состояние 0 (начальное): по 'a' -> 0, по 'b' -> 0, по 'a' -> 1
//   состояние 1:             по 'b' -> 2
//   состояние 2:             по 'a' -> 3
//   состояние 3 (конечное):  нет исходящих ребер
//
// В оригинальном проекте Visual Studio точкой входа обычно является
// _tmain(int argc, _TCHAR* argv[]) из <tchar.h>. Здесь используется
// стандартный int main() — их можно взаимозаменять без изменения логики.

#include "FST.h"
#include <iostream>
#include <clocale>
#include <cstring>

// Небольшой помощник, чтобы не дублировать вывод результата разбора
void report(FST::FST& fst, const char* comment)
{
    bool ok = FST::execute(fst);
    std::cout << "Цепочка \"" << fst.string << "\" "
              << (ok ? "распознана" : "не распознана")
              << "  (" << comment << ")" << std::endl;
}

int main()
{
    setlocale(LC_ALL, "rus");

    // ---------------------------------------------------------------
    // 1) Базовый пример из задания (рис. 2) — эталонная строка
    // ---------------------------------------------------------------
    FST::FST fst1(
        "aaabbbaba",
        4,
        FST::NODE(3, FST::RELATION('a', 0), FST::RELATION('b', 0), FST::RELATION('a', 1)),
        FST::NODE(1, FST::RELATION('b', 2)),
        FST::NODE(1, FST::RELATION('a', 3)),
        FST::NODE()
    );
    report(fst1, "эталонный пример из задания");

    // Демонстрация работы алгоритма "на двух массивах" (п.13):
    // после execute() в fst1.rstates лежит итоговое состояние по каждой
    // вершине графа переходов: -1, если вершина недостижима, и число
    // разобранных символов, на котором она была достигнута, если достижима.
    std::cout << "  rstates для \"" << fst1.string << "\": ";
    for (short i = 0; i < fst1.nstates; i++)
        std::cout << "[" << i << "]=" << fst1.rstates[i] << " ";
    std::cout << "(длина цепочки = " << strlen(fst1.string) << ")" << std::endl;

    // ---------------------------------------------------------------
    // 2) Минимальная распознаваемая цепочка
    // ---------------------------------------------------------------
    FST::FST fst2(
        "aba",
        4,
        FST::NODE(3, FST::RELATION('a', 0), FST::RELATION('b', 0), FST::RELATION('a', 1)),
        FST::NODE(1, FST::RELATION('b', 2)),
        FST::NODE(1, FST::RELATION('a', 3)),
        FST::NODE()
    );
    report(fst2, "минимальная цепочка вида aba");

    // ---------------------------------------------------------------
    // 3) Цепочка с произвольным префиксом из {a,b}, распознаётся
    // ---------------------------------------------------------------
    FST::FST fst3(
        "bbbaaaba",
        4,
        FST::NODE(3, FST::RELATION('a', 0), FST::RELATION('b', 0), FST::RELATION('a', 1)),
        FST::NODE(1, FST::RELATION('b', 2)),
        FST::NODE(1, FST::RELATION('a', 3)),
        FST::NODE()
    );
    report(fst3, "произвольный префикс + aba, распознаётся");

    // ---------------------------------------------------------------
    // 4) Ещё одна распознаваемая цепочка (длинный префикс)
    // ---------------------------------------------------------------
    FST::FST fst4(
        "ababababa",
        4,
        FST::NODE(3, FST::RELATION('a', 0), FST::RELATION('b', 0), FST::RELATION('a', 1)),
        FST::NODE(1, FST::RELATION('b', 2)),
        FST::NODE(1, FST::RELATION('a', 3)),
        FST::NODE()
    );
    report(fst4, "длинный префикс + aba, распознаётся");

    // ---------------------------------------------------------------
    // 5) п.9 задания: разбор проходит ВСЕ символы входной цепочки,
    //    но цепочка не распознаётся (обрыв на предпоследнем состоянии)
    // ---------------------------------------------------------------
    FST::FST fst5(
        "aaabbbab",
        4,
        FST::NODE(3, FST::RELATION('a', 0), FST::RELATION('b', 0), FST::RELATION('a', 1)),
        FST::NODE(1, FST::RELATION('b', 2)),
        FST::NODE(1, FST::RELATION('a', 3)),
        FST::NODE()
    );
    report(fst5, "п.9: все символы разобраны, но не распознана");

    // ---------------------------------------------------------------
    // 6) п.10 задания: разбор завершается, НЕ перебрав все символы.
    //    Символ 'c', отсутствующий в алфавите автомата, стоит в СЕРЕДИНЕ
    //    цепочки -> все состояния становятся недостижимы и execute()
    //    прекращает разбор, не дойдя до конца строки (position < strlen).
    // ---------------------------------------------------------------
    FST::FST fst6(
        "aacbba",
        4,
        FST::NODE(3, FST::RELATION('a', 0), FST::RELATION('b', 0), FST::RELATION('a', 1)),
        FST::NODE(1, FST::RELATION('b', 2)),
        FST::NODE(1, FST::RELATION('a', 3)),
        FST::NODE()
    );
    bool ok6 = FST::execute(fst6);
    std::cout << "Цепочка \"" << fst6.string << "\" "
              << (ok6 ? "распознана" : "не распознана")
              << "  (п.10: остановка на позиции " << fst6.position
              << " из " << strlen(fst6.string) << " символов)" << std::endl;

    // ---------------------------------------------------------------
    // 7) Ещё один не распознаваемый вариант
    // ---------------------------------------------------------------
    FST::FST fst7(
        "abab",
        4,
        FST::NODE(3, FST::RELATION('a', 0), FST::RELATION('b', 0), FST::RELATION('a', 1)),
        FST::NODE(1, FST::RELATION('b', 2)),
        FST::NODE(1, FST::RELATION('a', 3)),
        FST::NODE()
    );
    report(fst7, "не распознаётся: не оканчивается на aba");

    // ---------------------------------------------------------------
    // п.11 задания: ещё 2 цепочки, не распознаваемые автоматом
    // ---------------------------------------------------------------
    FST::FST fst8(
        "bbb",
        4,
        FST::NODE(3, FST::RELATION('a', 0), FST::RELATION('b', 0), FST::RELATION('a', 1)),
        FST::NODE(1, FST::RELATION('b', 2)),
        FST::NODE(1, FST::RELATION('a', 3)),
        FST::NODE()
    );
    report(fst8, "п.11 (1/2): не содержит aba вовсе");

    FST::FST fst9(
        "aabba",
        4,
        FST::NODE(3, FST::RELATION('a', 0), FST::RELATION('b', 0), FST::RELATION('a', 1)),
        FST::NODE(1, FST::RELATION('b', 2)),
        FST::NODE(1, FST::RELATION('a', 3)),
        FST::NODE()
    );
    report(fst9, "п.11 (2/2): оканчивается на bba, а не на aba");

    return 0;
}
