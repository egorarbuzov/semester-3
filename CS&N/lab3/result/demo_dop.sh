#!/bin/bash
#
# Одноразовая демонстрация: задержка внутри критической секции сервера
# при параллельном соединении нескольких клиентов.
#
# Нужен запущенный dop_server3, собранный из исходника, где в listAll()
# стоит sleep(5) между pthread_mutex_lock и pthread_mutex_unlock.
#
# Запуск:  ./demo_dop.sh [число клиентов]      (по умолчанию 3)

DIR="$(cd "$(dirname "$0")" && pwd)"
CLIENT="$DIR/client_dop_test"
N="${1:-3}"

if ! nc -z 127.0.0.1 1280 2>/dev/null; then
    echo "Сервер не запущен. Запусти: ./dop_server3"
    exit 1
fi

echo "Отправляю $N клиентов одновременно (LIST)..."
echo "Ожидаемо при sleep(5) внутри критической секции: 5.2 с, 10.2 с, 15.2 с"
echo "Если задержки в сервере нет — у всех будет около 0.2 с."
echo

for ((i = 0; i < N; i++)); do
    ( "$CLIENT" LIST | grep '^\[time\]' | sed "s/^/клиент $((i + 1)): /" ) &
done
wait
